#!/usr/bin/env python3
"""Generate docs/<service>/methods/<name>.md and docs/<service>/events/<name>.md from catalog/."""
import json
import os
import sys

import specload as S


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ").strip() or "-"


def type_of(sch):
    t = sch.get("type")
    if "oneOf" in sch and not t:
        t = [b.get("type", "?") for b in sch["oneOf"]]
    if isinstance(t, list):
        t = "|".join(t)
    if t == "array":
        item = sch.get("items") or {}
        t = "array<%s>" % (type_of(item) if item else "any")
    return t or "any"


def notes_of(sch):
    bits = []
    if sch.get("description"):
        bits.append(sch["description"])
    if "const" in sch:
        bits.append("Fixed value `%s`." % json.dumps(sch["const"]))
    if "enum" in sch:
        bits.append("One of: %s." % ", ".join("`%s`" % v for v in sch["enum"]))
    rng = []
    if "minimum" in sch:
        rng.append(">= %s" % sch["minimum"])
    if "maximum" in sch:
        rng.append("<= %s" % sch["maximum"])
    if "minItems" in sch:
        rng.append("at least %s item(s)" % sch["minItems"])
    if rng:
        bits.append("Range: %s." % ", ".join(rng))
    conf = sch.get("x-confidence")
    if conf:
        bits.append("[%s]" % conf)
    return " ".join(bits)


def flatten(sch, prefix="", variant=None, rows=None):
    """Flatten an object schema into table rows (name, type, required, default, notes)."""
    rows = rows if rows is not None else []
    if "oneOf" in sch and "properties" not in sch:
        for branch in sch["oneOf"]:
            flatten(branch, prefix, branch.get("title"), rows)
        return rows
    props = sch.get("properties") or {}
    required = set(sch.get("required", []))
    dep = {}
    for trigger, needed in (sch.get("dependentRequired") or {}).items():
        for n in needed:
            dep[n] = trigger
    for name, sub in props.items():
        path = prefix + name
        if name in required:
            req = "yes"
        elif name in dep:
            req = "if `%s` present" % dep[name]
        elif sub.get("x-required-when"):
            req = "if %s" % sub["x-required-when"]
        else:
            req = "no"
        if "default" in sub:
            default = json.dumps(sub["default"])
        else:
            default = sub.get("x-default", "-")
        notes = notes_of(sub)
        rows.append({"name": path, "type": type_of(sub), "req": req, "default": default,
                     "notes": notes, "raw": notes, "variant": variant})
        if sub.get("type") == "object" or "properties" in sub:
            flatten(sub, path + ".", variant, rows)
        elif sub.get("type") == "array" and isinstance(sub.get("items"), dict) and (
                "properties" in sub["items"] or sub["items"].get("type") == "object"):
            flatten(sub["items"], path + "[].", variant, rows)
    return rows


def merge_variants(rows):
    """Collapse rows that are identical across oneOf branches; keep differing ones per variant."""
    out, index = [], {}
    for r in rows:
        key = (r["name"], r["type"], r["req"], r["default"], r["raw"])
        if key in index:
            first = index[key]
            if first["variant"] != r["variant"]:
                first["variant"] = "both"
            continue
        index[key] = r
        out.append(r)
    for r in out:
        if r["variant"]:
            r["notes"] = "(%s) %s" % (r["variant"], r["raw"])
    return out


def table(rows, headers=("Name", "Type", "Required", "Default", "Notes")):
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        lines.append("| `%s` | %s | %s | %s | %s |" % (
            r["name"], cell(r["type"]), cell(r["req"]), cell(r["default"]), cell(r["notes"])))
    return "\n".join(lines)


def examples(entry, of_kinds, heading_for):
    out = []
    for ex in entry.get("examples", []):
        if ex["of"] not in of_kinds:
            continue
        label = ex.get("name", "example")
        if ex.get("summary"):
            label += " - " + ex["summary"]
        out.append("%s, %s:\n\n```json\n%s\n```" % (heading_for(ex["of"]), label,
                                                    json.dumps(ex["payload"], separators=(",", ":"))))
    return out


GENERATED = "<!-- Generated by tools/gen_cards.py from catalog/. Do not edit by hand. -->"


def card(e, siblings, service):
    name, kind = e["name"], ("methods" if e["kind"] == "method" else "events")
    L = ["# `%s`" % name, "",
         GENERATED, "",
         e.get("summary", "").strip(), "", "## Summary", "",
         "| Item | Value |", "|---|---|",
         "| Kind | %s |" % ("method (client sends)" if kind == "methods" else "event (device sends)"),
         "| Grade | %s |" % cell(e.get("grade")),
         "| Side-effect tier | %s |" % cell(e.get("side_effect_tier")),
         "| Confidence | %s |" % cell(e.get("confidence")),
         "| Basis | %s |" % cell(e.get("basis")), ""]
    if e.get("description"):
        L += [" ".join(e["description"].split()), ""]
    if e.get("side_effects"):
        L += ["Side effects: %s" % " ".join(e["side_effects"].split()), ""]

    L += ["## Request params", ""]
    if kind == "methods":
        L += [table(merge_variants(flatten(e["request"]))), ""]
    else:
        L += ["None. Events are sent by the device without a request; the payload is below.", ""]

    L += ["## Reply" if kind == "methods" else "## Payload", ""]
    payload = {"oneOf": [e["reply_success"], e["reply_error"]]} if kind == "methods" else e["payload"]
    L += [table(merge_variants(flatten(payload))), ""]

    L += ["## Errors", ""]
    errs = e.get("errors")
    if errs:
        L += ["| Code | Trigger | Label |", "|---|---|---|"]
        L += ["| %s | %s | `%s` |" % (r["code"], cell(r["trigger"]), r["label"]) for r in errs]
        if e.get("errors_note"):
            L += ["", e["errors_note"]]
        L += [""]
    else:
        L += ["None. Failures appear in the payload (`code`, `error`) when `state` is `fail`.", ""]

    L += ["## Example", ""]
    if kind == "methods":
        ex = examples(e, ("request",), lambda k: "Request") + examples(
            e, ("reply_success", "reply_error"), lambda k: "Reply")
    else:
        ex = examples(e, ("payload",), lambda k: "Event")
    L += ["\n\n".join(ex) if ex else "None recorded.", ""]

    L += ["## See also", ""]
    links = []
    for link in S.spec_links(e):
        path, _, anchor = link.partition("#")
        title, anchors = S.headings(path)
        text = title or path
        if anchors.get(anchor):
            text = "%s: %s" % (text, anchors[anchor])
        links.append("- [%s](../../../%s)" % (text.replace("`", ""), link))
    for other in (e.get("see_also") or []):
        svc, _, nm = other.rpartition("/")
        sub = siblings.get((svc or service, nm))
        if sub:
            target = "../%s/%s.md" % (sub, nm) if not svc or svc == service else "../../%s/%s/%s.md" % (svc, sub, nm)
            links.append("- [`%s`](%s)" % (other, target))
    L += links or ["- None"]
    return "\n".join(L).rstrip() + "\n"


def card_index(svc, summary, rows, retired):
    L = ["# `%s` cards" % svc, "", GENERATED, "", summary, ""]
    for kind, heading in (("method", "Methods"), ("event", "Events")):
        sub = [r for r in rows if r[0] == kind]
        if sub:
            L += ["## " + heading, "", "| Name | Summary |", "|---|---|"]
            L += ["| [`%s`](%s/%s.md) | %s |" % (n, kind + "s", n, cell(s)) for _, n, s in sub]
            L += [""]
    if retired:
        L += ["## Retired", "", "Kept so that old links still resolve; each page names its replacement.", ""]
        L += ["- [`%s`](%s/%s.md)" % (n, kind + "s", n) for kind, n in retired] + [""]
    return "\n".join(L).rstrip() + "\n"


def top_index(services):
    L = ["# Reference cards", "", GENERATED, "",
         "One page per catalogued method and event, generated from `catalog/`. Services whose "
         "protocols are documented only in prose have no cards.", "", "| Service | Summary |", "|---|---|"]
    L += ["| [`%s`](%s/index.md) | %s |" % (s, s, cell(summary)) for s, summary in services]
    return "\n".join(L) + "\n"


def render_all():
    """{repo-relative path: content} for everything under docs/."""
    siblings = {(svc, en["name"]): ("methods" if en["kind"] == "method" else "events")
                for svc, en in S.all_entries()}
    out, rows, problems = {}, {}, []
    for svc, en in S.all_entries():
        e = S.load_entry(svc, en["file"])
        sub = siblings[(svc, e["name"])]
        out["docs/%s/%s/%s.md" % (svc, sub, e["name"])] = card(e, siblings, svc)
        rows.setdefault(svc, []).append((e["kind"], e["name"], e.get("summary", "").strip()))
    retired = {}
    for svc, kind, name, rel in S.retired_entries():
        path = "docs/%s/%ss/%s.md" % (svc, kind, name)
        stub = os.path.join(S.ROOT, "tools", "card-stubs", svc, kind + "s", name + ".md")
        if path in out:
            problems.append("%s: retired entry is also active" % path)
        elif not os.path.exists(stub):
            problems.append("%s: retired entry needs a tombstone at %s" % (path, os.path.relpath(stub, S.ROOT)))
        else:
            out[path] = open(stub, encoding="utf-8").read()
            retired.setdefault(svc, []).append((kind, name))
    listed = []
    for s in S.load_index().get("services", []):
        svc = s["name"]
        if svc in rows or svc in retired:
            listed.append((svc, s.get("summary", "")))
            desc = S.load_service_index(svc).get("description") or s.get("summary", "")
            out["docs/%s/index.md" % svc] = card_index(svc, desc, rows.get(svc, []), sorted(retired.get(svc, [])))
    out["docs/index.md"] = top_index(listed)
    return out, problems


def existing():
    found = set()
    for d, _, files in os.walk(os.path.join(S.ROOT, "docs")):
        found.update(os.path.relpath(os.path.join(d, f), S.ROOT).replace(os.sep, "/") for f in files)
    return found


def check():
    """Problems if docs/ differs from what the catalog generates."""
    want, problems = render_all()
    have = existing()
    for path in sorted(set(want) | have):
        if path not in have:
            problems.append("%s: missing (run tools/gen_cards.py)" % path)
        elif path not in want:
            problems.append("%s: not generated by the catalog (stale card? retire it with a tombstone)" % path)
        elif open(os.path.join(S.ROOT, path), encoding="utf-8").read() != want[path]:
            problems.append("%s: differs from generated output (run tools/gen_cards.py)" % path)
    return problems


def main():
    if "--check" in sys.argv:
        problems = check()
        for p in problems:
            print("FAIL", p)
        return 1 if problems else 0
    want, problems = render_all()
    for p in problems:
        print("FAIL", p)
    if problems:
        return 1
    for path, text in want.items():
        os.makedirs(os.path.dirname(os.path.join(S.ROOT, path)), exist_ok=True)
        with open(os.path.join(S.ROOT, path), "w", encoding="utf-8") as fh:
            fh.write(text)
    for path in sorted(existing() - set(want)):
        os.remove(os.path.join(S.ROOT, path))
        print("removed " + path)
    print("wrote %d files" % len(want))
    return 0


if __name__ == "__main__":
    sys.exit(main())
